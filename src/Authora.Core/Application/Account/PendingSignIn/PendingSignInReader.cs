using Authora.Core.Abstractions;
using Authora.Core.Application.Account.SecondFactors;
using Authora.Core.Domain.Entities;

using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

namespace Authora.Core.Application.Account.PendingSignIn;

/// <summary>
///     Loads a pending sign-in by the token from its cookie and checks that it can still be completed.
/// </summary>
/// <param name="challengeRepository">An Instance of a ISignInChallengeRepository to load the pending sign-in.</param>
/// <param name="userRepository">An Instance of a IUserRepository to load the User.</param>
/// <param name="sessionRepository">An Instance of a ISessionRepository to load the Session of a step-up.</param>
/// <param name="secondFactors">The second factors, to find those the User still has to complete.</param>
/// <param name="secretHasher">The hasher to look up the token.</param>
/// <param name="timeProvider">The TimeProvider for the expiry checks.</param>
/// <param name="options">The sign-in settings with the idle timeout of Sessions.</param>
/// <param name="logger">The Logger to record why a pending sign-in can no longer be completed.</param>
public sealed class PendingSignInReader(
    ISignInChallengeRepository challengeRepository,
    IUserRepository userRepository,
    ISessionRepository sessionRepository,
    SecondFactorRegistry secondFactors,
    ISecretHasher secretHasher,
    TimeProvider timeProvider,
    IOptions<SignInOptions> options,
    ILogger<PendingSignInReader> logger)
{
    /// <summary>
    ///     Tokens are generated by <see cref="ISecretGenerator"/> and much shorter. Longer values are not looked up.
    /// </summary>
    public const int MaxTokenLength = 256;

    /// <summary>
    ///     Loads the pending sign-in and checks it.
    /// </summary>
    /// <remarks>
    ///     It cannot be completed if it is unknown, completed, expired, its User can no longer sign in or has another
    ///     <see cref="User.SecurityStamp"/>, no enrolled factor is left to complete, or, for a step-up, its Session ended
    ///     or is not the Session of the browser.
    /// </remarks>
    /// <param name="challengeToken">The plain-text token from the cookie.</param>
    /// <param name="currentSessionId">Id of the Session of the browser, or null if it has none.</param>
    /// <param name="cancellationToken">CancellationToken to cancel the request.</param>
    /// <returns>The pending sign-in with its tracked User, or null if it cannot be completed.</returns>
    public async Task<PendingSignInState?> ReadAsync(string? challengeToken, Guid? currentSessionId, CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrEmpty(challengeToken) || challengeToken.Length > MaxTokenLength)
        {
            return null;
        }

        var challenge = await challengeRepository.GetChallengeByTokenHash(secretHasher.Hash(challengeToken), cancellationToken);

        if (challenge is null)
        {
            return null;
        }

        var now = timeProvider.GetUtcNow().UtcDateTime;

        if (challenge.ConsumedAt is not null)
        {
            return Reject(challenge, "it was already completed");
        }

        if (challenge.IsExpired(now))
        {
            return Reject(challenge, "it expired");
        }

        var user = await userRepository.GetUserById(challenge.UserId, cancellationToken);

        if (user is null || !user.CanSignIn)
        {
            return Reject(challenge, "the User cannot sign in");
        }

        if (!challenge.IsFor(user))
        {
            return Reject(challenge, "the Security Stamp of the User changed");
        }

        Session? session = null;

        if (challenge.SessionId is { } sessionId)
        {
            session = await sessionRepository.GetSessionById(sessionId, cancellationToken);

            if (session is null
                || session.Id != currentSessionId
                || session.UserId != user.Id
                || session.SecurityStamp != user.SecurityStamp
                || !session.IsActive(now, options.Value.SessionIdleTimeout))
            {
                return Reject(challenge, "the Session of the step-up ended or is not the Session of the browser");
            }
        }

        var completed = challenge.AuthenticationMethods;
        var factors = (await secondFactors.GetEnrolledAsync(user.Id, cancellationToken))
            .Where(factor => !completed.Contains(factor.Method, StringComparer.Ordinal))
            .ToList();

        if (factors.Count == 0)
        {
            return Reject(challenge, "no second factor is left to complete");
        }

        return new PendingSignInState(challenge, user, session, factors);
    }

    private PendingSignInState? Reject(SignInChallenge challenge, string reason)
    {
        logger.PendingSignInRejected(challenge.Id, reason);

        return null;
    }
}

/// <summary>
///     A pending sign-in that can still be completed.
/// </summary>
/// <param name="Challenge">The pending sign-in.</param>
/// <param name="User">The tracked User who is signing in.</param>
/// <param name="Session">The tracked Session of a step-up, or null for a new sign-in.</param>
/// <param name="Factors">The enrolled factors the User can complete, at least one.</param>
public sealed record PendingSignInState(
    SignInChallenge Challenge,
    User User,
    Session? Session,
    IReadOnlyList<ISecondFactor> Factors);
